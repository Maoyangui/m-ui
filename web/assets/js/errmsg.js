// 固定称呼:填进占位里的端口归属、证书文件,以及数据面重载的操作名(noteReload),只做整句查表
const LABELS = /*LABELS*/{
"面板": "Panel", "订阅": "Subscription", "代理面板": "Reseller panel", "证书": "Certificate", "私钥": "Private key",
"启动": "Start", "全量重载": "Full reload", "热换出站": "Outbound hot swap", "热更新用户": "User hot update", "撤销凭据": "Credential revocation"
}/*END*/;

const VERB = /%(?:\[(\d+)\])?[-+# 0-9.]*[dsvqwxf]/g;
const quote = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const exact = new Map(Object.entries(LABELS));
const patterns = [];
for (const [zh, en] of Object.entries(EN)) {
  const re = new RegExp(VERB.source, 'g');
  const parts = [];
  let last = 0, lit = 0, m;
  const verbs = [];
  while ((m = re.exec(zh))) {
    parts.push(quote(zh.slice(last, m.index)));
    lit += m.index - last;
    verbs.push(m[0].slice(-1));
    last = re.lastIndex;
  }
  if (!verbs.length) { exact.set(zh, en); continue; }
  parts.push(quote(zh.slice(last)));
  lit += zh.length - last;
  // 先要求每个占位至少一个字,再放宽到可以为空:否则 "端口 %d 已被本机其它程序占用" 会被前面多一个空 %s 的 "%s端口 …" 抢走
  const re1 = new RegExp('^' + parts.join('([\\s\\S]+?)') + '$');
  const re0 = new RegExp('^' + parts.join('([\\s\\S]*?)') + '$');
  patterns.push({ re1, re0, verbs, en, lit });
}
patterns.sort((a, b) => b.lit - a.lit); // 字面越长越具体,先比:"已被本机其它程序占用" 要先于 "已被%s占用"

function tr(msg, depth) {
  const hit = exact.get(msg);
  if (hit !== undefined) return hit;
  if (depth > 4) return msg;
  for (const key of ['re1', 're0']) {
    for (const p of patterns) {
      const m = p[key].exec(msg);
      if (!m) continue;
      const groups = m.slice(1).map((g, i) => (p.verbs[i] === 'w' || p.verbs[i] === 'v') ? tr(g, depth + 1) : (exact.get(g) ?? g));
      let next = 0;
      return p.en.replace(VERB, (_, n) => { const i = n ? Number(n) - 1 : next; next = i + 1; return groups[i] ?? ''; });
    }
  }
  return msg;
}

// trErr 把后端返回的错误换成当前界面语言;中文界面原样返回。
export function trErr(msg) {
  if (!msg || getLang() === 'zh') return msg;
  return tr(String(msg), 0);
}
